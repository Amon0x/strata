// Compiles the raster kernels (gpu/raster_shaders.hpp) once, at build time, into the header
// raster_pass.cpp embeds: no run of an application waits on fxc for them.

#include <cstddef>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <sstream>
#include <string>
#include <string_view>

#define WIN32_LEAN_AND_MEAN
#define NOMINMAX
#include <Windows.h>
#include <d3dcompiler.h>
#include <wrl/client.h>

#include "gpu/raster_shaders.hpp"

namespace {

using Microsoft::WRL::ComPtr;
namespace shaders = strata::gpu::raster_shaders;

/** A kernel's bytecode; `finish` writes RGBA, the rest R8 coverage. */
[[nodiscard]] ComPtr<ID3DBlob> compile(const char* const entry) {
    const D3D_SHADER_MACRO rgba[]{{"STRATA_RASTER_RGBA", "1"}, {nullptr, nullptr}};
    ComPtr<ID3DBlob> code;
    ComPtr<ID3DBlob> diagnostics;
    const HRESULT status = D3DCompile(
        shaders::source.data(), shaders::source.size(), "strata.d3d11.raster.hlsl",
        std::string_view(entry) == "finish" ? rgba : nullptr, nullptr, entry, "cs_5_0",
        D3DCOMPILE_ENABLE_STRICTNESS | D3DCOMPILE_OPTIMIZATION_LEVEL3, 0U, &code, &diagnostics);
    if (FAILED(status)) {
        if (diagnostics != nullptr) {
            std::fwrite(diagnostics->GetBufferPointer(), 1U, diagnostics->GetBufferSize(), stderr);
        }
        return nullptr;
    }
    return code;
}

} // namespace

int main(const int argument_count, char** const arguments) {
    if (argument_count != 2) {
        std::fputs("usage: strata_d3d11_raster_bake output.hpp\n", stderr);
        return 2;
    }
    std::ostringstream header;
    header << "// Generated by strata_d3d11_raster_bake from gpu/raster_shaders.hpp: do not edit.\n"
              "#pragma once\n\n#include <array>\n#include <cstdint>\n#include <span>\n\n"
              "namespace strata::d3d11::raster_bytecode {\n\n";
    for (std::size_t index = 0U; index < shaders::entries.size(); ++index) {
        const ComPtr<ID3DBlob> code = compile(shaders::entries[index]);
        if (code == nullptr) {
            std::fprintf(stderr, "strata_d3d11_raster_bake: %s did not compile\n",
                         shaders::entries[index]);
            return 1;
        }
        const auto* const bytes = static_cast<const unsigned char*>(code->GetBufferPointer());
        header << "/** " << shaders::entries[index] << " */\ninline constexpr std::uint8_t kernel_"
               << index << "[] = {";
        for (std::size_t byte = 0U; byte < code->GetBufferSize(); ++byte)
            header << (byte % 24U == 0U ? "\n    " : " ") << static_cast<unsigned>(bytes[byte]) << ',';
        header << "\n};\n\n";
    }
    header << "/** The kernels' bytecode, in gpu::raster_shaders::entries' order. */\n"
              "inline constexpr std::array<std::span<const std::uint8_t>, "
           << shaders::entries.size() << "U> kernels{";
    for (std::size_t index = 0U; index < shaders::entries.size(); ++index)
        header << (index == 0U ? "" : ", ") << "kernel_" << index;
    header << "};\n\n} // namespace strata::d3d11::raster_bytecode\n";

    // An unchanged header keeps its time, so nothing that includes it rebuilds.
    const std::string text = header.str();
    {
        std::ifstream existing(arguments[1], std::ios::binary);
        if (existing && std::string(std::istreambuf_iterator<char>(existing), {}) == text)
            return 0;
    }
    std::ofstream output(arguments[1], std::ios::binary | std::ios::trunc);
    output << text;
    return output ? 0 : 1;
}
