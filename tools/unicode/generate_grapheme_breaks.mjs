#!/usr/bin/env node
// Regenerates native/src/ui/input/grapheme_break_data.inc, the code point table behind the text
// editor's UAX #29 extended grapheme clusters.
//
//   node tools/unicode/generate_grapheme_breaks.mjs native/src/ui/input/grapheme_break_data.inc
//
// ECMAScript exposes Regional_Indicator and Extended_Pictographic directly but not
// Grapheme_Cluster_Break or Indic_Conjunct_Break, so every scalar value is classified by how the
// runtime's own UAX #29 segmenter (Intl.Segmenter, ICU) treats it beside known neighbours. Each
// probe isolates one rule, so the table is exactly the property data that segmenter uses; the
// Unicode version is the runtime's (process.versions.unicode) and is recorded in the output.

import { writeFileSync } from "node:fs";

const output = process.argv[2];
if (!output) {
    console.error("usage: node generate_grapheme_breaks.mjs <output.inc>");
    process.exit(2);
}

// Property byte layout, mirrored by native/src/ui/input/grapheme.cpp.
const GCB = {
    other: 0, cr: 1, lf: 2, control: 3, extend: 4, zwj: 5, regional_indicator: 6, prepend: 7,
    spacing_mark: 8, l: 9, v: 10, t: 11, lv: 12, lvt: 13,
};
const EXTENDED_PICTOGRAPHIC = 0x10;
const INCB = { none: 0x00, linker: 0x20, consonant: 0x40, extend: 0x60 };

const segmenter = new Intl.Segmenter("und", { granularity: "grapheme" });
// Whether the segmenter breaks between `before` and `after`.
const breaks = (before, after) => {
    for (const { index } of segmenter.segment(before + after)) {
        if (index === before.length) return true;
        if (index > before.length) return false;
    }
    return false;
};

const LETTER = "a";
const COMBINING = "̈";
const ZWJ = "‍";
const PICTOGRAPH = "\u{1F600}";
const CHOSEONG = "ᄀ";
const JUNGSEONG = "ᅡ";
const JONGSEONG = "ᆨ";
const KA = "क";
const VIRAMA = "्";

const regionalIndicator = /^\p{Regional_Indicator}$/u;
const pictographic = /^\p{Extended_Pictographic}$/u;

const classify = (value) => {
    const c = String.fromCodePoint(value);
    let gcb;
    if (value === 0x0d) gcb = GCB.cr;
    else if (value === 0x0a) gcb = GCB.lf;
    else if (value === 0x200d) gcb = GCB.zwj;
    else if (regionalIndicator.test(c)) gcb = GCB.regional_indicator;
    else if (breaks(c, COMBINING)) gcb = GCB.control; // GB4: only controls break before Extend.
    else if (!breaks(LETTER, c)) {
        // GB9/GB9a. Only Extend continues an emoji ZWJ sequence (GB11).
        gcb = breaks(PICTOGRAPH + c + ZWJ, PICTOGRAPH) ? GCB.spacing_mark : GCB.extend;
    } else if (!breaks(c, LETTER)) gcb = GCB.prepend; // GB9b
    else if (!breaks(c, CHOSEONG)) gcb = GCB.l; // GB6: L x L
    else if (!breaks(c, JUNGSEONG)) gcb = breaks(JUNGSEONG, c) ? GCB.lv : GCB.v; // GB6/GB7
    else if (!breaks(c, JONGSEONG)) gcb = breaks(JUNGSEONG, c) ? GCB.lvt : GCB.t; // GB7/GB8
    else gcb = GCB.other;

    let incb = INCB.none;
    if (gcb === GCB.extend || gcb === GCB.zwj) {
        // GB9c: a linker alone joins two consonants; an extend joins them only after a linker.
        if (!breaks(KA + c, KA)) incb = INCB.linker;
        else if (!breaks(KA + VIRAMA + c, KA)) incb = INCB.extend;
    } else if (gcb === GCB.other && !breaks(KA + VIRAMA, c)) {
        incb = INCB.consonant;
    }
    return gcb | incb | (pictographic.test(c) ? EXTENDED_PICTOGRAPHIC : 0);
};

const runs = [];
let previous = -1;
for (let value = 0; value <= 0x10ffff; ++value) {
    // Surrogates are not scalar values and never reach the editor (its text is valid UTF-8).
    const property = value >= 0xd800 && value <= 0xdfff ? GCB.control : classify(value);
    if (property !== previous) {
        runs.push([value, property]);
        previous = property;
    }
}

const lines = [];
for (let index = 0; index < runs.length; index += 6) {
    lines.push(
        "    " +
            runs
                .slice(index, index + 6)
                .map(([first, property]) =>
                    "0x" + ((first * 256 + property) >>> 0).toString(16).toUpperCase().padStart(8, "0") + "U,")
                .join(" "),
    );
}

const header = `// Generated by tools/unicode/generate_grapheme_breaks.mjs; do not edit.
// Unicode ${process.versions.unicode} (Node ${process.version}, ICU ${process.versions.icu}): every
// scalar classified through Intl.Segmenter's UAX #29 extended grapheme cluster rules. See
// native/src/ui/quick_pick_unicode.LICENSE for the Unicode data license.
//
// Each entry is (first code point << 8) | property and covers code points up to the next entry's
// first. Property: bits 0-3 Grapheme_Cluster_Break, bit 4 Extended_Pictographic, bits 5-6
// Indic_Conjunct_Break (1 Linker, 2 Consonant, 3 Extend).
`;
writeFileSync(
    output,
    `${header}inline constexpr std::string_view grapheme_data_unicode_version = "${process.versions.unicode}";
inline constexpr std::array<std::uint32_t, ${runs.length}U> grapheme_break_runs{{
${lines.join("\n")}
}};
`,
);
console.log(`${output}: ${runs.length} runs, Unicode ${process.versions.unicode}`);
